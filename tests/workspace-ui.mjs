  assert.equal(await page.locator("#proc-table tr.row").count(),2);
  await page.locator('[data-select-connector]').first().click();
  if(!await page.locator('.focus-card').count()) await page.locator('[data-select-connector]').first().click();
  await page.locator('.focus-card [data-workspace-jump="kits"]').click();
  await page.getByRole("link",{name:"Download complete kit",exact:true}).waitFor();
  await page.screenshot({path:"/tmp/openxpli-workspace-kit.png",fullPage:true});
  await page.evaluate(()=>{
    window.__procs[0].map="## Campaigns\n**Brand campaign** is active.\n- Budget: $100/day\n- Goal: qualified visits\n\n<script>window.evidenceUnsafe=true</script>";
    window.__evidenceCandidates=window.__procs[0].candidates;
    window.__procs[0].candidates=[{...window.__procs[0].candidates[0],evidence:[{url:"https://ads.example.test/campaigns/brand",text:"Brand campaign: $100/day",observedAt:1700000000000},{url:"javascript:alert(1)",text:"Untrusted source",observedAt:null}]}];
    openKnowledge(window.__procs[0].id);
  });
  const evidenceDialog=page.getByRole("dialog",{name:"Account evidence",exact:true});
  await evidenceDialog.getByRole("heading",{name:"Campaigns",exact:true}).waitFor();
  assert.ok(await evidenceDialog.locator('.evidence-source').count()>=2);
  assert.equal(await evidenceDialog.locator('a[href^="javascript:"]').count(),0);
  assert.equal(await page.evaluate(()=>window.evidenceUnsafe),undefined);
  await evidenceDialog.getByText("Read captured page text",{exact:true}).first().click();
  await evidenceDialog.getByText("Brand campaign: $100/day",{exact:true}).waitFor();
  await page.screenshot({path:"/tmp/openxpli-account-evidence.png"});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await evidenceDialog.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.keyboard.press("Escape");
  assert.equal(await evidenceDialog.count(),0);
  await page.evaluate(()=>{window.__procs[0].candidates=window.__evidenceCandidates;});
  await page.setViewportSize({width:1440,height:1100});
