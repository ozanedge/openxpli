  assert.equal(page.context().pages().length,1,"adding a connector must not open an unrelated auth tab");
  await page.locator('[data-workspace-filter="ready"]').click();
  await page.reload();
  assert.equal(await page.locator('[data-workspace-filter="ready"]').getAttribute("aria-pressed"),"true");
  await page.locator('#proc-table tr.row').waitFor();
  assert.equal(await page.locator('#proc-table tr.row').count(),1);
  await page.locator('[data-workspace-filter="all"]').click();
  await page.locator('[data-select-connector="ads-openai/main-account"]').first().click();
  if(!await page.locator('.focus-card').count()) await page.locator('[data-select-connector="ads-openai/main-account"]').first().click();
