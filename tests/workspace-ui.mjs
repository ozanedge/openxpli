  assert.equal(await context.getAttribute("open"),"");
  // Destructive controls are available without expanding the connector.
  await page.locator('.connector-menu summary').first().click();
  await page.getByRole("button",{name:"Delete connector",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await dialog.waitFor();
  await page.locator('#form-submit').focus();
  await page.keyboard.press("Tab");
  assert.equal(await page.evaluate(()=>document.activeElement.getAttribute("aria-label")),"Close dialog");
  await page.locator('#form-submit').click();
  await page.locator('#form-error').getByText("Cancel the browser task",{exact:false}).waitFor();
  assert.equal(await page.locator('#form-submit').isEnabled(),true);
  await page.keyboard.press("Escape");
  assert.equal(await dialog.count(),0);
  assert.equal(await page.locator('#view-processes').evaluate(el=>el.inert),false);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.getElementById("view-processes").scrollTo(0,0));
  await page.screenshot({path:"/tmp/openxpli-workspace-mobile.png",fullPage:true});
  await page.locator('.focus-card [data-workspace-jump="kits"]').click();
  await page.screenshot({path:"/tmp/openxpli-workspace-mobile-kit.png",fullPage:true});
  const overflow=await page.evaluate(()=>({body:document.body.scrollWidth,viewport:innerWidth,main:document.getElementById("view-processes").scrollWidth,client:document.getElementById("view-processes").clientWidth}));
  assert.ok(overflow.body<=overflow.viewport && overflow.main<=overflow.client,JSON.stringify(overflow));
  await page.setViewportSize({width:1440,height:1100});
  await page.getByRole("button",{name:"Add connector",exact:false}).first().click();
  await page.getByRole("dialog",{name:"Bring an account into focus"}).waitFor();
